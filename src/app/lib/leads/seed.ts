export const seedLeads: Lead[] = seedInput.map((item) => {
  const createdAt = isoDaysAgo(item.createdDaysAgo, 10);
  const lastActivityAt = isoDaysAgo(item.lastActivityDaysAgo, 14);
  const followUpAt = item.followUpInDays === null ? null : isoDaysFromNow(item.followUpInDays, 16);

  const base = {
    id: item.id,
    name: item.name,
    email: item.email,
    phone: item.phone,
    vehicle_interest: item.vehicle,
    vehicle_category: item.category,
    budget: item.budget,
    status: item.status,
    source_platform: item.source,
    assigned_to: item.assignedTo,
    assigned_initials: repInitials(item.assignedTo),
    assigned_color: repColorByName[item.assignedTo] ?? "bg-gray-500",
    created_at: createdAt,
    last_activity_at: lastActivityAt,
    follow_up_at: followUpAt,
    financing: item.financing,
    trade_in: item.tradeIn,
    notes: [item.note],
    updated_by: "System",
  };

  const score = computeLeadScore({
    status: base.status,
    source_platform: base.source_platform,
    budget: base.budget,
    trade_in: base.trade_in,
    financing: base.financing,
    last_activity_at: base.last_activity_at,
    follow_up_at: base.follow_up_at,
  });

  const priority = derivePriorityBand(score);
  const nextAction = suggestNextAction({ status: base.status, follow_up_at: base.follow_up_at });

  return {
    ...base,
    score,
    priority_band: priority,
    next_action: nextAction,
  };
});

